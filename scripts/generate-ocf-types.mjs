#!/usr/bin/env node
/**
 * Generates src/types/ocf.generated.ts directly from the canonical OCF schema
 * in the spec package (`@opencoachingformat/spec`, or a local checkout during
 * development — see SCHEMA_PATH below).
 *
 * This file replaces a hand-written src/types/ocf.ts that had drifted from the
 * real schema (wrong court.drill_focus enum, a nonexistent top-level `version`
 * field, a truncated `meta`, non-functional `branches`, mismatched
 * `color_scheme` keys, and missing `Area`/`Label` frame overlays). Codegen
 * makes that class of drift structurally impossible: this script runs on every
 * `npm run build` / `npm test` (see package.json `pretest`/`prebuild` hooks),
 * so the types are always exactly what the schema says, not a snapshot of it.
 *
 * DO NOT hand-edit the generated output. If a type needs to change, change the
 * schema (in the spec repo) and regenerate.
 */
import { compile } from "json-schema-to-typescript";
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

// During local dev without the published spec package yet, fall back to a
// sibling checkout of opencoachingformat/spec (i.e. ../spec next to this
// repo's own root, not inside it). Once @opencoachingformat/spec ships
// schema/v1.json as a package export, switch SCHEMA_PATH to that
// require.resolve(...) call and delete the fallback branch.
const SCHEMA_PATH = (() => {
  try {
    return require.resolve("@opencoachingformat/spec/schema/v1.json");
  } catch {
    return resolve(__dirname, "../../spec/schema/v1.json");
  }
})();

const OUT_PATH = resolve(__dirname, "../src/types/ocf.generated.ts");

async function main() {
  const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf-8"));

  const banner = `/**
 * AUTO-GENERATED — DO NOT EDIT BY HAND.
 *
 * Generated by scripts/generate-ocf-types.mjs from the canonical OCF schema
 * at: ${SCHEMA_PATH}
 * Schema version: ${schema.$id ?? schema.title ?? "unknown"}
 *
 * To change these types, change the schema and re-run:
 *   npm run generate:types
 */
`;

  let ts = await compile(schema, "OpenCoachingFormat", {
    bannerComment: banner,
    additionalProperties: false,
    style: { semi: true, singleQuote: false },
  });

  // json-schema-to-typescript emits `State`/`State1` as a plain index
  // signature (`[k: string]: Coordinate`) plus a `balls?: {...}` property.
  // TypeScript rejects that combination (TS2411: a named property's type
  // must be assignable to the index signature's type) even though the
  // schema itself is unambiguous — `state` in schema/v1.json (see
  // definitions.state) reserves `balls` via `properties` and covers every
  // other key via `patternProperties`, with `additionalProperties: false`.
  // Rather than hand-maintain a divergent replacement, patch the two
  // generated interfaces post-hoc into an equivalent shape TS accepts:
  // `balls` pulled out of the index signature via `Omit`, expressed as an
  // intersection. This keeps the fix mechanically tied to the schema's
  // `state` definition — if that definition's key pattern changes, this
  // regex still finds `interface State/State1 { balls?: ...; [k: string]: Coordinate; }`
  // and the shape stays correct; only a hard schema-shape change (not a mere
  // field addition) would require touching this function.
  ts = ts.replace(
    /export interface (State1?) \{\n  balls\?: \{\n    \[k: string\]: BallState;\n  \};\n  \[k: string\]: Coordinate;\n\}/g,
    (_match, name) =>
      `export type ${name} = {\n  [entityRef: string]: Coordinate;\n} & {\n  balls?: {\n    [k: string]: BallState;\n  };\n};`
  );

  // Same class of json-schema-to-typescript limitation as above, on
  // definitions.ball_state: its `oneOf` (exactly one of carried_by/at/dead,
  // each with a `not: anyOf [...]` mutual-exclusion) doesn't translate to a
  // TS discriminated union — the generator instead emits a flat optional-
  // properties object intersected with a `BallState1` union of three
  // identical, useless `{ [k: string]: unknown }` branches. That leaves every
  // property optional, so `"carried_by" in ballState` doesn't narrow
  // `ballState.carried_by` to a definite string the way the schema's "exactly
  // one of" actually guarantees. Replace both with the discriminated union
  // the schema means: `{ carried_by } | { at } | { dead: true }`. Tied to the
  // literal generated shape, so a real schema change (not just a mechanical
  // regen) is what would make this stop matching.
  ts = ts.replace(
    /export type BallState = \{\n  carried_by\?: EntityRef;\n  at\?: Coordinate;\n  dead\?: true;\n\} & BallState1;\nexport type BallState1 =\n  \| \{\n      \[k: string\]: unknown;\n    \}\n  \| \{\n      \[k: string\]: unknown;\n    \}\n  \| \{\n      \[k: string\]: unknown;\n    \};/,
    `export type BallState =\n  | { carried_by: EntityRef }\n  | { at: Coordinate }\n  | { dead: true };`
  );

  // definitions.ball has the identical oneOf/not/anyOf shape as ball_state
  // above (a ball's initial state also carries exactly one of
  // carried_by/at/dead, plus a required `id`), and hits the same generator
  // limitation. Same fix, with `id` kept as its own required field. `Ball`
  // and its `Ball1` helper aren't declared adjacently (json-schema-to-
  // typescript orders declarations by dependency, not by usage site), so
  // they're matched and dropped separately.
  ts = ts.replace(
    /export type Ball = \{\n  id: BallRef;\n  carried_by\?: EntityRef;\n  at\?: Coordinate;\n  dead\?: true;\n\} & Ball1;/,
    `export type Ball = { id: BallRef } & (\n  | { carried_by: EntityRef }\n  | { at: Coordinate }\n  | { dead: true }\n);`
  );
  ts = ts.replace(/export type Ball1 = \{\n  \[k: string\]: unknown;\n\};\n/, "");

  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, ts);
  console.log(`[generate-ocf-types] wrote ${ts.length} chars to ${OUT_PATH}`);
}

main().catch((err) => {
  console.error("[generate-ocf-types] FAILED:", err.message);
  console.error(
    "Is the spec schema available? Expected either the " +
      "@opencoachingformat/spec package, or a sibling checkout of " +
      "opencoachingformat/spec (../spec next to this repo) with schema/v1.json."
  );
  process.exit(1);
});
